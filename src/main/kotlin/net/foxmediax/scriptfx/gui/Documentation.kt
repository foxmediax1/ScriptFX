        cameraSMALLText "текст" "время показа (3.sec)" - показывает по середине экрана маленький текст на указанное время.
        ---
        ВАЖНОЕ ПРИМЕЧАНИЕ:

        Если в конце команды "cameraBIGText" добавить "+smalltext" и на следующей строке написать "cameraSMALLText", то оба текста появятся и исчезнут одновременно: маленький встанет под большим. В этом случае время в "cameraSMALLText" можно не указывать.

        Эти команды не ждут окончания эффекта. Чтобы следующая команда выполнилась после него, добавьте "ticktime" с тем же временем.
        ---
        Пример скрипта:

        cameraINEffect "2.sec"
        ticktime "2.sec"
        cameraBIGText "Глава 1" "4.sec" +smalltext
        cameraSMALLText "Начало пути"
        ticktime "4.sec"
        cameraOUTEffect

        Если экран завис в чёрном, используйте команду /scriptfx camera_reset.
        ---
    """.trimIndent().lines()

    private val CUTSCENES: List<String> = """
    Раздел: "Катсцены"
    ---
    Катсцена - это эпизод, в котором камера уходит от игрока и движется по заданным точкам. Игрок в это время может быть заблокирован, а интерфейс скрыт. Катсцена начинается командой "cutscene_start" и заканчивается командой "cutscene_end". Все остальные команды этого раздела работают только внутри катсцены.
    ---
    1. Начало и конец:

    cutscene_start "player или all" - начинает катсцену. "player" - только для игрока, к которому привязан скрипт, "all" - для всех игроков. Если режим не указан, используется "player". Повторный запуск у игрока, который уже в катсцене, ничего не меняет.

    cutscene_end - завершает катсцену и возвращает игрока на то место, где он стоял перед её началом.
    ---
    2. Положение камеры:

    camera_set x y z поворот наклон - мгновенно ставит камеру в точку. "y" - это высота самой камеры. Поворот: 0 - на юг, 90 - на запад, 180 - на север, -90 - на восток. Наклон: от -90 (вверх) до 90 (вниз), 0 - прямо перед собой. Шестым аргументом можно указать тип мира (overworld, nether, end).

    camera_move x y z поворот наклон "время" - плавно двигает камеру из текущего положения в указанное. Скрипт ждёт окончания движения. Если время не указано, оно равно 1.sec.
    ---
    3. Путь камеры из нескольких точек:

    camera_path_start - начинает запись пути.

    camera_path_point x y z поворот наклон "время" - добавляет точку. Время - сколько камера летит до этой точки от предыдущей.

    camera_path_end - запускает записанный путь. Без дополнительных аргументов скрипт идёт дальше сразу, не дожидаясь конца пути. Если написать "camera_path_end wait", скрипт дождётся, пока камера пройдёт все точки.
    ---
    4. Куда смотреть и угол обзора:

    camera_lookat x y z "время" - поворачивает камеру на точку, не меняя её положения. Без времени поворот мгновенный, с указанием времени - плавный, и скрипт ждёт его окончания.

    camera_lookat_entity "ник игрока" "время" - то же самое, но камера смотрит на игрока. Вместо ника можно указать @s - игрок, к которому привязан скрипт.

    camera_fov число "время" - меняет угол обзора (от 10 до 170). Без времени меняется сразу, с указанием времени - плавно, и скрипт ждёт окончания. После катсцены угол обзора возвращается к настройке игрока.
    ---
    5. Игрок и экран:

    player_lock true или false - блокирует (true) или возвращает (false) управление: игрок не может двигаться и поворачивать камеру мышью.

    hud_hide true или false - скрывает или показывает интерфейс (хотбар, здоровье и т.д.).

    letterbox true или false "высота" - чёрные полосы сверху и снизу, как в кино. Высота - доля экрана от 0 до 0.4 (по умолчанию 0.15).
    ---
    Время во всех командах пишется так: "1.sec" (секунды), "0.5.sec" (доли секунды), "20.tick" (тики), "500.ms" (миллисекунды).
    ---
    Пример скрипта:

    cutscene_start all
    player_lock true
    hud_hide true
    letterbox true 0.12

    camera_set 100 70 200 0 10
    camera_fov 50 "1.sec"

    camera_path_start
    camera_path_point 110 72 210 45 5 "2.sec"
    camera_path_point 120 75 220 90 0 "3.sec"
    camera_path_end wait

    camera_lookat 100 65 200 "1.5.sec"
    camera_fov 70 "1.sec"

    letterbox false
    hud_hide false
    player_lock false
    cutscene_end
    ---
    Если что-то пошло не так:

    Ctrl + Alt + End - игрок сам прерывает катсцену: камера возвращается к нему, управление и интерфейс включаются.

    /scriptfx stop_all_scripts - останавливает все скрипты и завершает катсцены.

    /scriptfx camera_reset - убирает затемнение и тексты камеры (катсцену не завершает).

    /scriptfx reload - заново загружает скрипты с диска и завершает катсцены.
    ---
""".trimIndent().lines()

    private val TRIGGERS: List<String> = """
        Раздел: "Триггеры"
        ---
        Триггер - это команда, которая включает реакцию на событие. Триггеры: checkpoint, worldstartscript и trigger_globalplay. Их можно указывать на любой строчке скрипта.

