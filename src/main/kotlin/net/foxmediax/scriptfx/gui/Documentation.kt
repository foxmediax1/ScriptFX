        startscript "название скрипта" - запускает файл скрипта, может быть использован после триггера, например после "checkpoint". Одновременно может работать не больше скриптов, чем указано в настройке "Макс. количество скриптов": остальные запуски отклоняются, об этом пишется в лог.
        ---
