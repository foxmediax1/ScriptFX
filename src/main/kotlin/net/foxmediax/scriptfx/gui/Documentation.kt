    npc_stop "id" — остановить движение сразу, анимация idle.

    Пример:
        npc_spawn "guard_01" ~ ~ ~
        npc_walk "guard_01" ~8 ~ ~ 0.35
        ticktime "4.sec"
        npc_stop "guard_01"
