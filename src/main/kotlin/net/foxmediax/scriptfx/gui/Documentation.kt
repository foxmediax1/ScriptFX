    private val NPC: List<String> = """
    Раздел: "Скрипты → NPC"
    ---
    Шаблон NPC - это файл id.fxnpc (формат JSON) в папке проекта: config/scriptfx/projects/название_проекта/npc/. Создавать и править шаблоны удобнее в панели управления: раздел "NPC-редактор" (справа 3D-превью, его можно вращать мышью).

    Поля шаблона:
    id - уникальное имя NPC, его пишут в командах.
    displayName - имя NPC: над головой и в окне диалога.
    model, texture, animation - ресурсы GeckoLib (см. ниже).
    defaultAnim - анимация при создании (по умолчанию idle).
    defaultMode - режим по умолчанию: dialog, interact, traiding.
    maxHealth - здоровье.
    invulnerable, lookAtPlayer, gravity, collide, nametag, silent - то же, что флаги Y_/N_ у npc_repack.
    speed, onInteractScript, interactKey - задаются в редакторе, но при создании NPC пока не применяются (клавишу ожидания задаёт команда npc_interact_key).

    Режимы NPC (defaultMode в шаблоне или последний аргумент npc_spawn):
    interact - рядом с NPC показывается подсказка клавиши взаимодействия.
    dialog - подсказки нет, диалог запускает скрипт командой npc_dialog_hud.
    traiding - зарезервирован под торговлю, отдельного поведения пока нет (подсказки клавиши нет).
    ---
    Модель, текстура, анимация:

    model и animation пишутся как "пространство:имя", например "scriptfx:female_models". Для модели мод берёт файл assets/пространство/geckolib/models/имя.geo.json, для анимации - файл с таким же именем в папке geckolib/animations (по соглашению GeckoLib 5). Если пространство не указано, используется scriptfx. Лишние части вроде "geckolib/models/" и ".geo.json" мод отбрасывает сам. Пустое значение - модель по умолчанию.

    texture - полный путь к картинке вместе с расширением, например "scriptfx:textures/npc/temple_skins.png".
    ---
    1. Создание и удаление:

    npc_spawn "id" x y z поворот наклон мир "анимация" "режим" - создаёт NPC. Всё после координат необязательно. Координаты - числа или "~" (позиция игрока скрипта): "~", "~5", "~-2". Поворот и наклон - два числа (0 - на юг, 90 - на запад, 180 - на север, -90 - на восток) или "~" (как у игрока), "~180" (у игрока плюс 180). Мир: overworld, nether или end, по умолчанию мир игрока. Если анимация или режим не указаны, берутся значения из шаблона NPC (раньше режим по умолчанию всегда был interact). Один NPC на один id.

    Примеры:
        npc_spawn "guard_01" 3 -60 -8
        npc_spawn "guard_01" ~ ~ ~ ~180 0 "idle" "dialog"
        npc_spawn "guard_01" 100 64 200 90 0 nether

    Анимации: idle, running, sprinting, crouching_idle, crouching, swipe, jump, land, stun1, stun1_idle, stun1_gettingUp, lying_idle, lying_running. Неизвестное название заменяется на idle.

    npc_despawn "id" - убирает NPC из мира.
    ---
    2. Изменение NPC:

    npc_repack "id" параметры - меняет уже созданного NPC. Параметров можно указать несколько через пробел. Пример: npc_repack "guard_01" N_look "anim=running" "name=Старый страж"

    Флаги Y_ (включить) и N_ (выключить):
    Y_damage / N_damage - NPC получает урон / неуязвим.
    Y_look / N_look - NPC смотрит на игрока / не смотрит.
    Y_gravity / N_gravity - гравитация.
    Y_nametag / N_nametag - показывать / скрыть имя над головой.
    Y_visible / N_visible - NPC виден / невидим.
    Y_silent / N_silent - NPC со звуками / без звуков.
    Y_collide / N_collide - NPC твёрдый / проходимый.

    Значения:
    anim=название - меняет анимацию.
    mode:режим - меняет режим (dialog, traiding, interact).
    name=Имя - меняет имя NPC (оно же показывается в окне диалога).
    hp число - задаёт здоровье.
    speed число - скорость движения.
    ---
    3. Поворот NPC:

    see_npc_K "id" x y z - NPC поворачивается лицом к точке. Координаты - числа или "~" (позиция игрока скрипта): "~", "~5", "~-2".

    see_npc_C "id" градус [наклон] - NPC поворачивается по горизонтали на указанный градус (0 - на юг, 90 - на запад, 180 - на север, -90 - на восток). Наклон головы (от -90 до 90) необязателен.

    Поворот мгновенный. Обе команды выключают у NPC флаг "смотреть на игрока" (как N_look): иначе NPC сразу отвернулся бы обратно. Чтобы вернуть слежку, используйте npc_repack "id" Y_look. Во время диалога NPC в любом случае разворачивается к игроку.

    Пример:
        npc_spawn "guard_01" 10 64 -20
        see_npc_K "guard_01" ~ ~ ~
        ticktime "2.sec"
        see_npc_C "guard_01" 180
    ---
    4. Ожидание клавиши:

    npc_interact_key "X" - скрипт останавливается и ждёт, пока игрок нажмёт указанную клавишу (по умолчанию X).
    ---
    5. Диалог с NPC:

    npc_dialog_hud "id" :: dialog_window_text "текст" :: button1 = "Ответ 1" :: button2 = "Ответ 2" - открывает окно диалога. Части команды разделяются знаком "::". Кнопок может быть до пяти (button1 ... button5). В тексте и на кнопках нельзя использовать "::".

    Скрипт ждёт выбора игрока, а номер выбранной кнопки записывается в переменную dialog_button. Обработать выбор можно командой if:

        npc_dialog_hud "guard_01" :: dialog_window_text "Кто идёт?" :: button1 = "Свой" :: button2 = "Прохожий" :: button3 = "Враг"

        if dialog_button == 1 {
        print "Проходи."
        }

        if dialog_button == 2 {
        print "Здесь нельзя задерживаться."
        }

    if сравнивает переменную со значением только через "==". Блок выполняется до строки "}" - её нужно писать всегда. Если выбор не сделан (игрок вышел из игры), dialog_button равна 0.

    Как выглядит диалог:
    - Слева: плашка с именем NPC (displayName) и под ней окно с текстом. Текст печатается по буквам. Если он не помещается, его можно листать колесом мыши. Если текст начинается с "Имя:", эта часть убирается, потому что имя уже показано в плашке.
    - Справа: кнопки с ответами. Длинный текст на кнопке переносится на новую строку, а кнопка становится выше.
    - Выбрать ответ можно мышью или клавишами 1-5. Клавиша ESC диалог не закрывает.
    - NPC, с которым идёт разговор, обводится белой линией. Обводку можно выключить в настройках мода: "Обводка NPC в диалоге".

    Камера в диалоге: NPC разворачивается лицом к игроку, камера плавно подъезжает к нему (угол обзора слегка сужается), а после выбора ответа так же плавно возвращается назад. На время диалога игрок не может двигаться и поворачивать камеру.

    Если NPC с таким id нет в мире, диалог всё равно откроется, но без камеры и обводки (в лог пишется предупреждение).
