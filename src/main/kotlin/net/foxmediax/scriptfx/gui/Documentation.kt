package net.foxmediax.scriptfx.gui

/**
 * Встроенная документация. Тексты лежат прямо в коде,
 * поэтому не зависят от файлов в ресурсах и конфиг-папке.
 * Строка DIVIDER рисуется как горизонтальная линия.
 */
object Documentation {

    const val DIVIDER = "---"

    fun page(section: String, subsection: String): List<String> = when {
        section == "Скрипты" && subsection == "Переменные" -> VARIABLES
        section == "Скрипты" && subsection == "Глобальные переменные" -> GLOBAL_VARIABLES
        section == "Скрипты" && subsection == "Для сюжета" -> STORY
        section == "Скрипты" && subsection == "Для камеры" -> CAMERA
        section == "Триггеры" -> TRIGGERS
        else -> emptyList()
    }

    private val VARIABLES: List<String> = """
        Раздел: "Переменные"
        ---
        print "текст" - присылает в чат определённый текст, без указания от кого оно.
        ---
        startCommand "команда" - выполняет определённую команду. (можно писать с "/", а можно и без неё)
        ---
    """.trimIndent().lines()

    private val GLOBAL_VARIABLES: List<String> = """
        Раздел: "Глобальные переменные"
        ---
        checkpoint "x" "y" "z" "тип мира" "радиус действия триггера(x, y, z) (числовой размер радиуса)" - триггер который можно расположить по оси x, y, z и указать размер радиуса действия, чтобы когда игрок зашёл в радиус, триггер уже сработал.
        ---
        startscript "название скрипта" - запускает файл скрипта, может быть использован после глобальной переменной "checkpoint".
        ---
        worldstartscript "название скрипта" - запускает файл скрипта во время того, как игрок зашёл в мир.
        ---
        tp_allplayers x y z "тип мира" - телепортирует всех игроков в мире в определённые координаты и измерение. Пример: tp_allplayers 0 64 0 overworld (типы мира: overworld, nether, end).
        ---
        ticktime "(время в секундах, указывается по примеру "1.sec")" - даёт определённую задержку в продолжении скрипта, после истечении указанного времени, скрипт продолжает свою работу.
        ---
        stopscript - завершает работу скрипта.
        ---
        continue_startscript "название файла скрипта.sfxs" - запускает следующий указанный файл скрипта, работает только после глобальной переменной "stopscript".
        ---
        trigger_globalplay "указать тип действия" - срабатывает только в том случае, если:
        1) Игрок попал в эндер мир и по этому миру уже летает эндер дракон. (ender_dragon_fight)
        2) Заспавнился босс-иссушитель. (wither_boss_fight)
        3) Игрок умер. (player_death)
        4) Игрок возродился. (player_respawn)
        5) Игрок телепортировался. (player_tp)
        6) Игрок поел еду. (player_eat)
        7) Игрок взаимодействовал с определённым предметом. (player_click "id предмета")
        ---
        weather "rain либо thunder" - срабатывает во время дождя или грозовой погоды.
        ---
        timecycles "day/night либо указать время в тиках" - срабатывает при наступлении определённого времени в игровом мире.
        ---
    """.trimIndent().lines()

    private val STORY: List<String> = """
        Раздел: "Скрипты для сюжета"
        ---
        1. Отправка сообщения в чат:

        printNPC "текст" "ID NPC либо никнейм" "цвет текста" - присылает в чат определённый текст от (никнейма/ID NPC). Имя и цвет можно не указывать.

        Пример скрипта:
        printNPC "Когда-то давно, мы жили мирно..." "Рассказчик" "aqua"

        В чате пишется так: [Имя] текст, с цветом который вы укажете.
        ---
    """.trimIndent().lines()

    private val CAMERA: List<String> = """
        Раздел: "Скрипты для камеры"
        ---
        1. Добавление эффекта появления и затухания:

        cameraINEffect "писать в секундах (1.sec)" - делает плавный эффект затухания в чёрный экран на определённое время, пока не произойдёт переменная "cameraOUTEffect" чёрный экран не пропадёт.

        cameraOUTEffect - убирает чёрный экран, делает эффект появления, используется только если была перед этим использованная переменная "cameraINEffect".

        cameraBIGText "Текст" "время отображения в секундах (1.sec)" - показывает по середине экрана большой текст на определённое время.

        cameraSMALLText "текст" "время отображения в секундах (1.sec)" - показывает по середине экрана маленький текст на определённое время.
        ---
        ВАЖНОЕ ПРИМЕЧАНИЕ:

        Если в конце переменной "cameraBIGText" добавить "+smalltext", и написать на следующей строке переменную "cameraSMALLText", то эти два текста отобразятся в одинаковое время и так же одинаково исчезнут. Если было указано "+smalltext" в переменной "cameraBIGText", то в переменной "cameraSMALLText" время отображения можно не указывать.
        ---
    """.trimIndent().lines()

    private val TRIGGERS: List<String> = """
        Раздел: "Триггеры"
        ---
        Триггер - это скрипт, у которого первая строка - служебная команда (checkpoint, worldstartscript, weather, timecycles или trigger_globalplay). Команды ниже неё выполняются, когда произошло нужное событие.

        Подробное описание каждой команды смотри в разделе Скрипты -> Глобальные переменные.
        ---
        Пример скрипта:
        checkpoint 100 64 200 overworld 5
        print "Вы дошли до точки!"
        ---
    """.trimIndent().lines()
}