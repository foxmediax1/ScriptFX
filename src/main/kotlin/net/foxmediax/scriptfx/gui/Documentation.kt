    private val NPC: List<String> = """
    Раздел: "Скрипты → NPC"
    ---
    Шаблон NPC хранится в папке проекта. При создании в редакторе структура такая:

    config/scriptfx/projects/<проект>/npc/<id>/
      <id>.fxnpc
      customs/
        models/        — свои .geo.json
        textures/      — свои .png
        animations/    — свои .animation.json

    Создавать и править шаблоны удобнее в панели: раздел «NPC-редактор» (справа 3D-превью, вращение мышью).
    Старый формат npc/<id>.fxnpc ещё читается; при сохранении переносится в npc/<id>/<id>.fxnpc.
    ---
    Поля шаблона (.fxnpc):

    id — уникальное имя NPC (в командах и имя папки).
    displayName — имя над головой и в окне диалога.
    model, texture, animation — ресурсы GeckoLib или customs:имя (см. ниже).
    defaultAnim — клип при спавне (обычно idle).
    defaultMode — dialog / interact / trading (допустимо traiding).
    maxHealth, speed — характеристики.
    invulnerable, lookAtPlayer, gravity, collide, nametag, silent — флаги (как Y_/N_ у npc_repack).
    onInteractScript, interactKey — скрипт и клавиша интеракции (клавишу ожидания в скрипте задаёт npc_interact_key).
    ---
    Режимы (defaultMode или аргумент npc_spawn):

    interact — подсказка клавиши рядом с NPC.
    dialog — без подсказки; диалог через npc_dialog_hud.
    trading — зарезервирован (отдельного UI пока нет).
    ---
    Стандартные модели (выбор при создании NPC):

    Female     — scriptfx:female_models + temple_female_skins.png
    Male       — scriptfx:male_models + temple_male_skins.png
    Male slim  — scriptfx:male_slim_models + temple_male_slim_skins.png

    Анимация набора: scriptfx:female_models / male_models / male_slim_models.
    ---
    Свои модели (папка customs, без resource pack):

    1) Создай NPC (или выбери «Своя (customs)» и укажи имя файлов без расширения).
    2) Положи файлы:

      .../npc/<id>/customs/models/<имя>.geo.json
      .../npc/<id>/customs/animations/<имя>.animation.json
      .../npc/<id>/customs/textures/<имя>.png

    3) В полях шаблона:

      model:     customs:<имя>
      animation: customs:<имя>
      texture:   customs:<имя>

    Мод читает файлы из папки проекта сам. Отдельный resource pack включать не нужно.
    После добавления или замены файлов: F3+T или перезаход в мир.

    Для встроенных моделей по-прежнему:
    model/animation — «пространство:имя» (например scriptfx:female_models);
    texture — полный путь с расширением (scriptfx:textures/npc/....png).
    ---
    1. Создание и удаление:

    npc_spawn "id" x y z поворот наклон мир "анимация" "режим" — создаёт NPC. Всё после координат необязательно.
    Координаты: число или "~" / "~5" / "~-2". Поворот и наклон: число или "~" / "~180".
    Мир: overworld, nether, end (по умолчанию мир игрока).
    Если анимация или режим не указаны — из шаблона. Один NPC на один id.

    Известные клипы анимации (зависит от набора): idle, running, sprinting, crouching_idle, crouching,
    swipe, jump, land, stun1, stun1_idle, stun1_gettingUp, lying_idle, lying_running.
    Неизвестное имя заменяется на idle.

    npc_despawn "id" — убирает NPC из мира.
    ---
    2. Изменение NPC:

    npc_repack "id" параметры — несколько параметров через пробел.
    Пример: npc_repack "guard_01" N_look "anim=running" "name=Старый страж"

    Флаги Y_ (вкл) / N_ (выкл):
    Y_damage / N_damage — урон / неуязвимость
    Y_look / N_look — смотреть на игрока
    Y_gravity / N_gravity — гравитация
    Y_nametag / N_nametag — имя над головой
    Y_visible / N_visible — видимость
    Y_silent / N_silent — звуки
    Y_collide / N_collide — коллизия

    Значения:
    anim=название — анимация
    mode:режим — dialog / interact / trading
    name=Имя — отображаемое имя
    hp число — здоровье
    speed число — скорость
    ---
    3. Поворот NPC:

    see_npc_K "id" x y z — смотреть в точку (число или ~).
    see_npc_C "id" градус [наклон] — поворот по горизонтали; наклон −90…90 необязателен.
    0 — юг, 90 — запад, 180 — север, −90 — восток.

    Поворот мгновенный. Обе команды выключают «смотреть на игрока» (как N_look).
    Вернуть слежку: npc_repack "id" Y_look. В диалоге NPC смотрит на игрока.

    Пример:
        npc_spawn "guard_01" 10 64 -20
        see_npc_K "guard_01" ~ ~ ~
        ticktime "2.sec"
        see_npc_C "guard_01" 180
    ---
    4. Ходьба:

    npc_walk "id" x y z [скорость] — NPC идёт к точке по прямой.
    Координаты: число или "~" / "~5" / "~-2".
    Скорость необязательна (по умолчанию 0.25, диапазон примерно 0.05–1.5).
