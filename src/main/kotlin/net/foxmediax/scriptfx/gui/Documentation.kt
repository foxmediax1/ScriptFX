package net.foxmediax.scriptfx.gui

/**
 * Встроенная документация. Тексты лежат прямо в коде,
 * поэтому не зависят от файлов в ресурсах и конфиг-папке.
 * Строка DIVIDER рисуется как горизонтальная линия.
 */
object Documentation {

    const val DIVIDER = "---"

    fun page(section: String, subsection: String): List<String> = when {
        section == "Скрипты" && subsection == "Переменные" -> VARIABLES
        section == "Скрипты" && subsection == "Глобальные переменные" -> GLOBAL_VARIABLES
        section == "Скрипты" && subsection == "Для сюжета" -> STORY
        section == "Скрипты" && subsection == "Для камеры" -> CAMERA
        section == "Триггеры" -> TRIGGERS
        section == "Примеры скриптов" -> TEMPLES_SCRIPTS
        section == "Скрипты" && subsection == "Катсцены" -> CUTSCENES
        section == "Скрипты" && subsection == "NPC" -> NPC
        else -> emptyList()
    }

    private val VARIABLES: List<String> = """
        Раздел: "Переменные"
        ---
        print "текст" - присылает в чат определённый текст, без указания от кого оно.
        ---
        startCommand "команда" - выполняет определённую команду. (можно писать с "/", а можно и без неё)
        ---
    """.trimIndent().lines()

    private val GLOBAL_VARIABLES: List<String> = """
        Раздел: "Глобальные переменные"
        ---
        checkpoint "x" "y" "z" "тип мира" "радиус действия триггера(x, y, z) (числовой размер радиуса)" - триггер, который можно расположить по оси x, y, z и указать размер радиуса действия: когда игрок зашёл в радиус, триггер срабатывает. Можно указывать на любой строчке скрипта. Работает вне зависимости от того, как запущен скрипт.
        ---
        startscript "название скрипта" - запускает файл скрипта, может быть использован после триггера, например после "checkpoint". Одновременно может работать не больше скриптов, чем указано в настройке "Макс. количество скриптов": остальные запуски отклоняются, об этом пишется в лог.
        ---
        worldstartscript - триггер, срабатывает во время того, как игрок зашёл в мир. Можно указывать на любой строчке скрипта.
        ---
        tp_allplayers x y z "тип мира" - телепортирует всех игроков в мире в определённые координаты и измерение. Пример: tp_allplayers 0 64 0 overworld (типы мира: overworld, nether, end).
        ---
        ticktime "время" - даёт определённую задержку в продолжении скрипта. Время можно писать так: "1.sec" (секунды), "0.5.sec" (доли секунды), "20.tick" (тики), "500.ms" (миллисекунды). После задержки скрипт продолжает свою работу.
        ---
        stopscript - завершает работу скрипта.
        ---
        continue_startscript "название файла скрипта.sfxs" - запускает следующий указанный файл скрипта, работает только после глобальной переменной "stopscript".
        ---
        trigger_globalplay "указать тип действия" - триггер, срабатывает только в том случае, если:
        1) Игрок попал в эндер мир и по этому миру уже летает эндер дракон. (ender_dragon_fight)
        2) Заспавнился босс-иссушитель. (wither_boss_fight)
        3) Игрок умер. (player_death)
        4) Игрок возродился. (player_respawn)
        5) Игрок телепортировался. (player_tp)
        6) Игрок поел еду. (player_eat)
        7) Игрок взаимодействовал с определённым предметом. (player_click "id предмета")
        Можно указывать на любой строчке скрипта.
        ---
        weather "rain, thunder либо clear" - меняет погоду в мире: дождь, гроза или ясная погода. Можно указывать на любой строчке скрипта.
        ---
        timecycles "day/night либо время в тиках" - меняет время суток в мире. Можно указывать на любой строчке скрипта.
        ---
    """.trimIndent().lines()

    private val STORY: List<String> = """
        Раздел: "Скрипты для сюжета"
        ---
        1. Отправка сообщения от имени NPC:

        printNPC "аватар.png" "текст" "цвет имени" "имя" "цвет текста" "ремарка" - показывает текст от имени NPC. Аватар (PNG до 64 КБ из папки avatars проекта) и ремарка необязательны. Если первый аргумент оканчивается на .png, он считается аватаром. Всё остальное, кроме текста, тоже можно не указывать, но порядок менять нельзя: чтобы задать имя, нужно указать и цвет имени.
        
        ---
        Пример скрипта:
        
        printNPC "Когда-то давно, мы жили мирно..." "gold" "Рассказчик" "aqua"

        Выводится так: [Имя] текст. Имя окрашено в "цвет имени", а текст — в "цвет текста".
        
        Пример скрипта с аватаром: 
        
        printNPC "рассказчик.png" "Когда-то давно, мы жили мирно..." "gold" "Рассказчик" "aqua"
        ---
    """.trimIndent().lines()

    private val CAMERA: List<String> = """
        Раздел: "Скрипты для камеры"
        ---
        1. Эффект затемнения экрана:

        cameraINEffect "время в секундах (1.sec)" - плавно затемняет экран до чёрного за указанное время. Экран остаётся чёрным, пока не выполнится команда "cameraOUTEffect". Если время не указано, оно равно 1.sec.

        cameraOUTEffect - плавно убирает чёрный экран за то же время, которое было указано в "cameraINEffect". Работает только если перед этим было затемнение.
        ---
        2. Текст по центру экрана:

        cameraBIGText "текст" "время показа (3.sec)" - показывает по середине экрана большой текст на указанное время.

        cameraSMALLText "текст" "время показа (3.sec)" - показывает по середине экрана маленький текст на указанное время.
        ---
        ВАЖНОЕ ПРИМЕЧАНИЕ:

        Если в конце команды "cameraBIGText" добавить "+smalltext" и на следующей строке написать "cameraSMALLText", то оба текста появятся и исчезнут одновременно: маленький встанет под большим. В этом случае время в "cameraSMALLText" можно не указывать.

        Эти команды не ждут окончания эффекта. Чтобы следующая команда выполнилась после него, добавьте "ticktime" с тем же временем.
        ---
        Пример скрипта:

        cameraINEffect "2.sec"
        ticktime "2.sec"
        cameraBIGText "Глава 1" "4.sec" +smalltext
        cameraSMALLText "Начало пути"
        ticktime "4.sec"
        cameraOUTEffect

        Если экран завис в чёрном, используйте команду /scriptfx camera_reset.
        ---
    """.trimIndent().lines()

    private val CUTSCENES: List<String> = """
    Раздел: "Катсцены"
    ---
    Катсцена - это эпизод, в котором камера уходит от игрока и движется по заданным точкам. Игрок в это время может быть заблокирован, а интерфейс скрыт. Катсцена начинается командой "cutscene_start" и заканчивается командой "cutscene_end". Все остальные команды этого раздела работают только внутри катсцены.
    ---
    1. Начало и конец:

    cutscene_start "player или all" - начинает катсцену. "player" - только для игрока, к которому привязан скрипт, "all" - для всех игроков. Если режим не указан, используется "player". Повторный запуск у игрока, который уже в катсцене, ничего не меняет.

    cutscene_end - завершает катсцену и возвращает игрока на то место, где он стоял перед её началом.
    ---
    2. Положение камеры:

    camera_set x y z поворот наклон - мгновенно ставит камеру в точку. "y" - это высота самой камеры. Поворот: 0 - на юг, 90 - на запад, 180 - на север, -90 - на восток. Наклон: от -90 (вверх) до 90 (вниз), 0 - прямо перед собой. Шестым аргументом можно указать тип мира (overworld, nether, end).

    camera_move x y z поворот наклон "время" - плавно двигает камеру из текущего положения в указанное. Скрипт ждёт окончания движения. Если время не указано, оно равно 1.sec.
    ---
    3. Путь камеры из нескольких точек:

    camera_path_start - начинает запись пути.

    camera_path_point x y z поворот наклон "время" - добавляет точку. Время - сколько камера летит до этой точки от предыдущей.

    camera_path_end - запускает записанный путь. Без дополнительных аргументов скрипт идёт дальше сразу, не дожидаясь конца пути. Если написать "camera_path_end wait", скрипт дождётся, пока камера пройдёт все точки.
    ---
    4. Куда смотреть и угол обзора:

    camera_lookat x y z "время" - поворачивает камеру на точку, не меняя её положения. Без времени поворот мгновенный, с указанием времени - плавный, и скрипт ждёт его окончания.

    camera_lookat_entity "ник игрока" "время" - то же самое, но камера смотрит на игрока. Вместо ника можно указать @s - игрок, к которому привязан скрипт.

    camera_fov число "время" - меняет угол обзора (от 10 до 170). Без времени меняется сразу, с указанием времени - плавно, и скрипт ждёт окончания. После катсцены угол обзора возвращается к настройке игрока.
    ---
    5. Игрок и экран:

    player_lock true или false - блокирует (true) или возвращает (false) управление: игрок не может двигаться и поворачивать камеру мышью.

    hud_hide true или false - скрывает или показывает интерфейс (хотбар, здоровье и т.д.).

    letterbox true или false "высота" - чёрные полосы сверху и снизу, как в кино. Высота - доля экрана от 0 до 0.4 (по умолчанию 0.15).
    ---
    Время во всех командах пишется так: "1.sec" (секунды), "0.5.sec" (доли секунды), "20.tick" (тики), "500.ms" (миллисекунды).
    ---
    Пример скрипта:

    cutscene_start all
    player_lock true
    hud_hide true
    letterbox true 0.12

    camera_set 100 70 200 0 10
    camera_fov 50 "1.sec"

    camera_path_start
    camera_path_point 110 72 210 45 5 "2.sec"
    camera_path_point 120 75 220 90 0 "3.sec"
    camera_path_end wait

    camera_lookat 100 65 200 "1.5.sec"
    camera_fov 70 "1.sec"

    letterbox false
    hud_hide false
    player_lock false
    cutscene_end
    ---
    Если что-то пошло не так:

    Ctrl + Alt + End - игрок сам прерывает катсцену: камера возвращается к нему, управление и интерфейс включаются.

    /scriptfx stop_all_scripts - останавливает все скрипты и завершает катсцены.

    /scriptfx camera_reset - убирает затемнение и тексты камеры (катсцену не завершает).

    /scriptfx reload - заново загружает скрипты с диска и завершает катсцены.
    ---
""".trimIndent().lines()

    private val TRIGGERS: List<String> = """
        Раздел: "Триггеры"
        ---
        Триггер - это команда, которая включает реакцию на событие. Триггеры: checkpoint, worldstartscript и trigger_globalplay. Их можно указывать на любой строчке скрипта.

        Триггер работает вне зависимости от того, как запущен скрипт. Когда происходит нужное событие, выполняются команды, которые стоят ниже строчки с триггером, до следующего триггера (или до конца файла).

        Команды выше триггера выполняются только при обычном запуске скрипта. При обычном запуске строчки с триггерами пропускаются, а остальные команды выполняются подряд.

        Команды weather и timecycles триггерами не являются: они сразу меняют погоду и время суток, когда до них доходит выполнение скрипта.

        Подробное описание каждой команды смотри в разделе Скрипты -> Глобальные переменные.
        ---
    """.trimIndent().lines()
    private val TEMPLES_SCRIPTS: List<String> = """
        Раздел: "Примеры скриптов" (подходит для начинающих)
        ---
        1. Триггеры:

            Триггеры (checkpoint, worldstartscript, trigger_globalplay) можно указывать на любой строчке скрипта.

        1) checkpoint 100 64 200 overworld 5

            Разберём данный скрипт:
            checkpoint - это триггер, который срабатывает, когда игрок зайдёт в определённую по размеру зону.
            100 64 200 - это можно разобрать как оси "x, y, z", в основном это координаты твоего местоположения в мире. Координаты можно посмотреть выйдя из панели управления мода ScriptFX и нажать горячую клавишу F3.
            overworld - это тип мира где вы хотите установить триггер.
            5 - это радиус действия, если игрок зайдёт в этот радиус, то триггер активируется.

        Чтобы понять что данный скрипт работает, то можно написать проверочный скрипт в скриптовый файл и запустить его.

        Пример скрипта:

            checkpoint 100 64 200 overworld 5
            print "Вы дошли до точки!"

        Пример с командами до триггера:

            print "Скрипт запущен вручную"
            trigger_globalplay player_death
            print "Вы погибли..."

        Если запустить этот скрипт вручную, выполнятся обе команды print. А когда игрок умрёт, выполнится только то, что стоит ниже триггера.
        ---
        2. Погода и время суток:

            weather thunder
            timecycles night

        Эти команды сразу меняют погоду и время суток, их можно ставить на любую строчку.
        ---
    """.trimIndent().lines()
    private val NPC: List<String> = """
        Раздел: "Скрипты → NPC"
        ---
        NPC описываются шаблонами в папке проекта: npcs/id.json (позже их будет создавать NPC-редактор). Режимы: Диалог (реплики по правому клику), Торговля (окно торговли), Интеракт (запуск скрипта по правому клику).
