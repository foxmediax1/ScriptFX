        section == "Скрипты" && subsection == "Катсцены" -> CUTSCENES
        section == "Скрипты" && subsection == "NPC" -> NPC
        section == "Скрипты" && subsection == "Кастомные модели NPC" -> CUSTOM_MODELS  // ← добавить
