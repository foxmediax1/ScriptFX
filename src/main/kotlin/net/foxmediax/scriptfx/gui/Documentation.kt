        ---
        tp_allplayers x y z "тип мира" - телепортирует всех игроков в мире в определённые координаты и измерение. Пример: tp_allplayers 0 64 0 overworld (типы мира: overworld, nether, end).
        ---
        trigger_globalplay "указать тип действия" - триггер, срабатывает только в том случае, если:
